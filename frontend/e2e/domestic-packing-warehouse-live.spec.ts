/** Only local rollback fixtures; never runs against real production credentials. */
import { expect, test } from "@playwright/test";
test.use({ channel: process.env.PLAYWRIGHT_CHANNEL, viewport: { width: 1920, height: 1080 } });
test.skip(process.env.PACKING_WAREHOUSE_E2E !== "1", "requires isolated local warehouse fixture bridge");
const prefix = "/api/pmc/domestic/packing-warehouse";
async function openWarehouse(page: import("@playwright/test").Page, writable: boolean) {
  await page.addInitScript(() => localStorage.setItem("szzsbj_auth_token", "synthetic-warehouse-ui"));
  await page.route("**/api/**", async (route) => {
    const url = new URL(route.request().url());
    if (!url.pathname.startsWith("/api/")) return route.fallback();
    if (url.pathname.startsWith(prefix)) return route.fulfill({ response: await route.fetch({ url: "http://127.0.0.1:8013" + url.pathname + url.search }) });
    const data = url.pathname === "/api/auth/me" ? { id: 15, username: "warehouse-fixture", display_name: "仓库本地验收", is_super_admin: false, role_keys: [], role_names: [], permissions: ["page:pmc:domestic-warehouse-board:view", ...(writable ? ["packing-boxes-save", "packing-done", "packing-customs", "packing-note", "packing-rebox", "packing-unpacked-dispose"].map((name) => "action:pmc:domestic-warehouse-board:" + name) : [])] }
      : url.pathname.endsWith("/filter-options") ? { stores: [], owners: [] } : { items: [], total: 0 };
    return route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ success: true, data, error: null, meta: { freshness_at: null, data_status: "not_published", publication_ids: [] }, request_id: "synthetic-warehouse-ui" }) });
  });
  await page.goto("/#/pmc/domestic/packing-warehouse");
  await expect(page.getByText("仓库打包单已接通本地数据", { exact: true })).toBeVisible();
}
test("read-only role sees approved PK with unavailable write actions", async ({ page }) => {
  await openWarehouse(page, false);
  await expect(page.getByRole("button", { name: "填装箱", exact: true }).first()).toBeDisabled();
  await expect(page.getByRole("button", { name: "改报关", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "延迟备注", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: /^详\s*情$/ }).first()).toBeEnabled();
  await expect(page.getByRole("columnheader", { name: /实际收货日/ })).toBeAttached();
});
test("draft, package completion, customs and notes use real local endpoints", async ({ page }, testInfo) => {
  await openWarehouse(page, true);
  const row = page.locator('.domestic-packing tr[data-row-key]').first();
  await expect(row).toContainText("FIXTURE-SKU");
  await row.getByRole("button", { name: "填装箱", exact: true }).click();
  let modal = page.getByRole("dialog", { name: "填写装箱数据", exact: true });
  await modal.getByRole("spinbutton", { name: "每箱件数" }).fill("3");
  await modal.getByRole("spinbutton", { name: "单箱毛重（kg）" }).fill("2.5");
  await modal.getByRole("textbox", { name: "数量差异原因" }).fill("先装三件等标签");
  let response = page.waitForResponse((r) => r.url().endsWith("/boxes") && r.request().method() === "POST");
  await modal.getByRole("button", { name: /^保\s*存$/ }).click();
  expect((await response).status()).toBe(200);
  await expect(modal).not.toBeVisible();
  await expect(row).toContainText("未装 2 件");
  await expect(row.getByRole("button", { name: "打包完成", exact: true })).toBeEnabled();
  await row.getByRole("button", { name: "打包完成", exact: true }).click();
  modal = page.getByRole("dialog", { name: "确认打包完成", exact: true });
  await modal.getByRole("combobox", { name: "少装原因" }).focus();
  await modal.getByRole("combobox", { name: "少装原因" }).press("ArrowDown");
  await page.locator('.ant-select-item-option[title="其他"]').click();
  await modal.getByRole("textbox", { name: "原因说明" }).fill("尾箱容纳不足");
  for (const [name, value] of [["单品包装长（cm）", "10"], ["单品包装宽（cm）", "8"], ["单品包装高（cm）", "3"], ["单品毛重（g）", "150"]]) await modal.getByRole("spinbutton", { name }).fill(value);
  response = page.waitForResponse((r) => r.url().endsWith("/done") && r.request().method() === "POST");
  await modal.getByRole("button", { name: "确认完成", exact: true }).click();
  const completed = await response;
  expect(completed.status()).toBe(200);
  expect((await completed.json()).data.box_set.package_snapshot.source).toBe("warehouse_measurement");
  await expect(modal).not.toBeVisible();
  await page.getByRole("button", { name: /^已打包待发\s*1$/ }).click();
  await expect(row).toContainText("已打包待发");
  await expect(row).toContainText("待中台处理");
  await row.getByRole("button", { name: "改装箱", exact: true }).last().click();
  modal = page.getByRole("dialog", { name: "改装箱（已完成单）", exact: true });
  await modal.getByRole("spinbutton", { name: "每箱件数" }).fill("5");
  await modal.getByRole("textbox", { name: "改装箱原因" }).fill("补齐尾箱并重新核对");
  response = page.waitForResponse((r) => r.url().endsWith("/rebox") && r.request().method() === "POST");
  await modal.getByRole("button", { name: /^保\s*存$/ }).click();
  expect((await response).status()).toBe(200);
  await expect(modal).not.toBeVisible();
  await expect(row).not.toContainText("待中台处理");
  await row.getByRole("button", { name: "改报关", exact: true }).click();
  modal = page.getByRole("dialog", { name: "修改是否报关", exact: true });
  await modal.getByRole("combobox", { name: "是否报关" }).focus();
  await modal.getByRole("combobox", { name: "是否报关" }).press("ArrowDown");
  await page.locator('.ant-select-item-option[title="报关"]').click();
  await modal.getByRole("textbox", { name: "修改原因" }).fill("按物流方式报关");
  response = page.waitForResponse((r) => r.url().endsWith("/customs") && r.request().method() === "POST");
  await modal.getByRole("button", { name: /^保\s*存$/ }).click();
  expect((await response).status()).toBe(200);
  await expect(modal).not.toBeVisible();
  await row.getByRole("button", { name: "延迟备注", exact: true }).click();
  modal = page.getByRole("dialog", { name: "填写延迟备注", exact: true });
  await modal.getByRole("combobox", { name: "原因分类" }).focus();
  await modal.getByRole("combobox", { name: "原因分类" }).press("ArrowDown");
  await page.locator('.ant-select-item-option[title="其他"]').click();
  await modal.getByRole("textbox", { name: "说明" }).fill("等待标签确认");
  response = page.waitForResponse((r) => r.url().endsWith("/notes") && r.request().method() === "POST");
  await modal.getByRole("button", { name: /^保\s*存$/ }).click();
  expect((await response).status()).toBe(200);
  await expect(modal).not.toBeVisible();
  await expect(row).toContainText("等待标签确认");
  await page.screenshot({ path: testInfo.outputPath("warehouse-packed.png"), fullPage: true });
  await row.getByRole("button", { name: /^详\s*情$/ }).click();
  await expect(page.getByRole("dialog", { name: "仓库打包单详情与审计", exact: true })).toContainText("打包完成");
});
