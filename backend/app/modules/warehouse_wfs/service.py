    def sync_legacy_cases(self, *, execute: bool) -> WfsFeeLegacySyncResult:
        # A production write requires separate authorization in addition to RBAC.
        if (
            execute
            and get_settings().app_env is AppEnvironment.PRODUCTION
            and os.getenv("WFS_CASE_SYNC_AUTHORIZED", "").casefold() != "true"
        ):
            raise ApiError(code=ErrorCode.FORBIDDEN, status_code=403)
        summary = self._legacy_sync_summary()
        if not execute:
            return summary
        if (
            summary.unmatched_identities
            or summary.ambiguous_identities
            or summary.duplicate_identities
            or summary.invalid_values
            or summary.case_ref_conflicts
        ):
            raise ApiError(code=ErrorCode.INVALID_REQUEST, status_code=409)
        result = self.session.execute(text(self._legacy_upsert_sql()))
        self.session.commit()
        return WfsFeeLegacySyncResult(
            **summary.model_dump(exclude={"execute", "inserted_or_updated"}),
            execute=True,
            inserted_or_updated=int(result.rowcount or 0),
        )

    def compare_legacy_cases(self) -> WfsFeeLegacyCompareResult:
        row = (
            self.session.execute(
                text(
                    """
                    with legacy as (
                      select
                        id legacy_case_id,
                        manual_fee,
                        actual_fee,
                        total_units affected_units,
                        est_recover estimated_recover_amount,
                        coalesce(recovered_amount, 0) recovered_amount,
                        nullif(trim(case_nos), '') case_nos,
                        claim_amount,
                        case status
                          when 'waiting' then 'pending_confirm'
                          when 'following' then 'following'
                          when 'approving' then 'archive_pending'
                          when 'closed' then 'archived'
                          when 'done' then 'recovered'
                        end expected_status
                      from legacy_mirror.event_wfs_fee_case
                      where platform = 'walmart'
                    ), formal as (
                      select
                        legacy_case_id,
                        manual_unit_fee,
                        actual_unit_fee,
                        affected_units,
                        estimated_recover_amount,
                        recovered_amount, nullif(trim(case_nos), '') case_nos,
                        claim_amount, status, updated_by
                      from ops_wfs_fee_anomaly_cases
                      where source_kind = 'legacy_mirror' and is_deleted = false
                    ), paired as (
                      select
                        l.legacy_case_id l_id,
                        f.legacy_case_id f_id,
                        l.manual_fee,
                        f.manual_unit_fee,
                        l.actual_fee,
                        f.actual_unit_fee,
                        l.affected_units l_units,
                        f.affected_units f_units,
                        l.estimated_recover_amount l_est,
                        f.estimated_recover_amount f_est,
                        l.recovered_amount l_recovered,
                        f.recovered_amount f_recovered,
                        l.case_nos l_case_nos,
                        f.case_nos f_case_nos,
                        l.claim_amount l_claim,
                        f.claim_amount f_claim,
                        l.expected_status,
                        f.status,
                        f.updated_by
                      from legacy l
                      full join formal f on f.legacy_case_id = l.legacy_case_id
                    )
                    select
                      count(*) filter (where l_id is not null and f_id is not null) compared,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and actual_fee is not distinct from actual_unit_fee
                          and manual_fee is not distinct from manual_unit_fee
                          and l_units is not distinct from f_units
                          and l_est is not distinct from f_est
                          and l_recovered is not distinct from f_recovered
                          and l_case_nos is not distinct from f_case_nos
                          and l_claim is not distinct from f_claim
                          and expected_status is not distinct from status
                      ) matched,
                      count(*) filter (where l_id is not null and f_id is null) only_in_legacy,
                      count(*) filter (where l_id is null and f_id is not null) only_in_formal,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and actual_fee is distinct from actual_unit_fee
                      ) actual_fee_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and manual_fee is distinct from manual_unit_fee
                      ) manual_fee_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and l_units is distinct from f_units
                      ) affected_units_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and l_est is distinct from f_est
                      ) estimated_recover_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and l_recovered is distinct from f_recovered
                      ) recovered_amount_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and l_case_nos is distinct from f_case_nos
                      ) case_nos_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and l_claim is distinct from f_claim
                      ) claim_amount_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and expected_status is distinct from status
                      ) status_diff,
                      count(*) filter (
                        where l_id is not null and f_id is not null
                          and updated_by is distinct from 'legacy_mirror'
                      ) protected_cases,
                      (select coalesce(sum(est_recover),0) from legacy_mirror.event_wfs_fee_case
                        where platform='walmart') legacy_estimated_total,
                      (select coalesce(sum(estimated_recover_amount),0) from formal)
                        formal_estimated_total,
                      (select coalesce(sum(recovered_amount),0)
                         from legacy_mirror.event_wfs_fee_case where platform='walmart')
                        legacy_recovered_total,
                      (select coalesce(sum(recovered_amount),0) from formal)
                        formal_recovered_total
                    from paired
                    """
                )
            )
            .mappings()
            .one()
        )
        return WfsFeeLegacyCompareResult(**dict(row))

    def _fetch_case_rows(
        self,
        query: WfsFeeCaseQuery,
        account_refs: frozenset[str],
    ) -> tuple[list[dict], int]:
        where = ["source_account_ref = any(:accounts)", "is_deleted = false"]
        params: dict[str, object] = {"accounts": list(account_refs)}
        if query.start_date is not None:
            where.append("coalesce(first_alert_at, created_at)::date >= :start_date")
            params["start_date"] = query.start_date
        if query.end_date is not None:
            where.append("coalesce(first_alert_at, created_at)::date <= :end_date")
            params["end_date"] = query.end_date
        if query.store_id is not None:
            where.append("store_id = :store_id")
            params["store_id"] = query.store_id
        if query.owner_ref is not None:
            where.append("owner_ref = :owner_ref")
            params["owner_ref"] = query.owner_ref
        if query.status is not None:
            where.append("status = :status")
            params["status"] = query.status
        if query.priority is not None:
            where.append("priority = :priority")
            params["priority"] = query.priority
        if query.archive_review_status is not None:
            where.append("archive_review_status = :archive_review_status")
            params["archive_review_status"] = query.archive_review_status
        if query.keyword:
            where.append(
                "(store_name_snapshot ilike :keyword or item_id ilike :keyword or "
                "msku ilike :keyword or case_nos ilike :keyword or "
                "owner_name_snapshot ilike :keyword or product_name_snapshot ilike :keyword)"
            )
            params["keyword"] = f"%{query.keyword}%"
        where_sql = " and ".join(where)
        total = int(
            self.session.execute(
                text(f"select count(*) from ops_wfs_fee_anomaly_cases where {where_sql}"),
                params,
            ).scalar_one()
        )
        params.update({"limit": query.page_size, "offset": (query.page - 1) * query.page_size})
        rows = (
            self.session.execute(
                text(
                    self._case_select_sql()
                    + f" where {where_sql} "
                    + " order by case status "
                    + " when 'archive_pending' then 1 "
                    + " when 'following' then 2 "
                    + " when 'pending_confirm' then 3 "
                    + " when 'recovered' then 4 "
                    + " else 5 end, estimated_recover_amount desc, updated_at desc "
                    + " limit :limit offset :offset"
                ),
                params,
            )
            .mappings()
            .all()
        )
        return [dict(row) for row in rows], total

    def _attach_product_management_fees(
        self,
        rows: list[dict],
        account_refs: frozenset[str],
    ) -> None:
        """Resolve Product Management WFS cost without ambiguous SKU matches."""
        if not rows:
            return

        for row in rows:
            row["product_management_unit_wfs_fee"] = None

        accounts = {
            str(row["source_account_ref"])
            for row in rows
            if row.get("source_account_ref") in account_refs
        }
        item_ids = {
            str(row["item_id"])
            for row in rows
            if row.get("source_account_ref") in accounts and row.get("item_id")
        }
        store_ids = {
            str(row["store_id"])
            for row in rows
            if row.get("source_account_ref") in accounts and row.get("store_id")
        }

        if not accounts or not item_ids or not store_ids:
            return

        listing_rows = (
            self.session.execute(
                text(
                    "select source_account_ref,store_id,item_id,msku,local_sku "
                    "from dim_walmart_listings "
                    "where source_account_ref=any(:accounts) "
                    "and store_id=any(:stores) and item_id=any(:items)"
                ),
                {
                    "accounts": sorted(accounts),
                    "stores": sorted(store_ids),
                    "items": sorted(item_ids),
                },
            )
            .mappings()
            .all()
        )

        listings = {
            (
                item["source_account_ref"],
                item["store_id"],
                item["item_id"],
            ): item
            for item in listing_rows
        }

        identity_rows = (
            self.session.execute(
                text(
                    "select i.id,i.source_account_ref,"
                    "i.lingxing_sku_code identity_sku,"
                    "p.sku product_sku,c.lingxing_sku_code current_sku "
                    "from dwd_lingxing_sku_identity_index i "
                    "left join products p "
                    "on p.id=i.product_id and p.deleted_at is null "
                    "left join dwd_lingxing_sku_product_info_current c "
                    "on c.identity_id=i.id "
                    "where i.source_account_ref=any(:accounts) "
                    "and i.is_active=true"
                ),
                {"accounts": sorted(accounts)},
            )
            .mappings()
            .all()
        )

        aliases: dict[tuple[str, str], set[str]] = {}

        for identity in identity_rows:
            account = str(identity["source_account_ref"])
            identity_id = str(identity["id"])

            for field in ("identity_sku", "product_sku", "current_sku"):
                key = normalize_sku_key(identity[field])
                if key:
                    aliases.setdefault((account, key), set()).add(identity_id)

        unique_skus: dict[str, set[str]] = {}

        for row in rows:
            account = str(row["source_account_ref"])
            if account not in accounts:
                continue

            listing = listings.get((account, row["store_id"], row["item_id"]))

            if listing is None:
                continue

            # Listing 和 WFS Case 必须属于同一个 MSKU。
            if not row.get("msku") or listing["msku"] != row["msku"]:
                continue

            sku = normalize_sku_key(listing["local_sku"])
            if not sku:
                continue

            # 同账号 SKU 对应多个产品身份时，不允许猜测。
            if len(aliases.get((account, sku), set())) != 1:
                continue

            unique_skus.setdefault(account, set()).add(sku)

        costs_by_account = {
            account: load_daily_sales_costs(
                self.session,
                source_account_ref=account,
            )
            for account in sorted(unique_skus)
        }

        for row in rows:
            account = str(row["source_account_ref"])
            if account not in costs_by_account:
                continue

            listing = listings.get((account, row["store_id"], row["item_id"]))
            if listing is None or listing["msku"] != row.get("msku"):
                continue

            sku = normalize_sku_key(listing["local_sku"])
            if sku not in unique_skus.get(account, set()):
                continue

            cost = costs_by_account[account].get(sku)
            if cost is not None:
                row["product_management_unit_wfs_fee"] = cost.wfs_fee_unit_usd

    def _to_alert_compat(self, row: dict) -> WfsFeeAlertRead:
        affected_units = Decimal(row["affected_units"] or 0)
        expected_total = (row["manual_unit_fee"] or Decimal("0")) * affected_units
        actual_total = (row["actual_unit_fee"] or Decimal("0")) * affected_units
        variance = row["estimated_recover_amount"] or Decimal("0")
        expected_unit = row["manual_unit_fee"]
        variance_rate = None
        if expected_total and expected_total > 0:
            variance_rate = variance / expected_total
        return WfsFeeAlertRead(
            id=row["id"],
            business_date_la=(row["first_alert_at"] or row["created_at"]).date(),
            store_id=row["store_id"],
            store_name=row["store_name_snapshot"],
            owner_ref=row["owner_ref"],
            item_id=row["item_id"],
            msku=row["msku"],
            local_sku=row["local_sku_snapshot"],
            product_name=row["product_name_snapshot"],
            order_count=affected_units,
            sales_qty=affected_units,
            cost_quantity=affected_units,
            expected_fee_amount=expected_total,
            actual_fee_amount=actual_total,
            variance_amount=variance,
            variance_rate=variance_rate,
            expected_unit_amount=expected_unit,
            actual_unit_amount=row["actual_unit_fee"],
            status=CASE_STATUS_TO_LABEL[row["status"]],
            case_no=row["case_nos"],
            reason=row["reason"] or row["archive_reason"],
            priority=PRIORITY_TO_LABEL[row["priority"]],
            claim_amount=row["claim_amount"],
            recovered_amount=row["recovered_amount"],
            pending_recovery_amount=row["pending_recover_amount"],
            case_opened_at=row["case_opened_at"],
            next_follow_at=row["next_follow_at"],
            latest_follow=row["latest_follow_note"] or row["follow_log"],
        )

