"""Fail-closed adapter for a separately approved Walmart bulk template.

No template is bundled or assumed to be current. This module is not exposed
as an API until an actual template, its SHA-256, and release authority exist.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping
from dataclasses import dataclass
from io import BytesIO
from xml.etree import ElementTree as ET
from zipfile import BadZipFile, ZipFile

from .internal_export import _make_xlsx

X = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
R = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"


class OfficialTemplateBlocked(ValueError):
    """Safe, machine-readable template or row-contract failure."""


@dataclass(frozen=True)
class OfficialTemplateContract:
    version: str
    sha256: str
    sheet_name: str
    headers: tuple[str, ...]
    approved_by: str
    approval_ref: str


def _template_headers(blob: bytes) -> tuple[str, tuple[str, ...]]:
    if not blob or len(blob) > 20 * 1024 * 1024:
        raise OfficialTemplateBlocked("TEMPLATE_SIZE_INVALID")
    try:
        with ZipFile(BytesIO(blob)) as archive:
            if (
                len(archive.infolist()) > 500
                or sum(x.file_size for x in archive.infolist()) > 65 * 1024 * 1024
            ):
                raise OfficialTemplateBlocked("TEMPLATE_ARCHIVE_UNSAFE")
            names = archive.namelist()
            if "xl/workbook.xml" not in names or "xl/_rels/workbook.xml.rels" not in names:
                raise OfficialTemplateBlocked("TEMPLATE_STRUCTURE_INVALID")
            workbook = ET.fromstring(archive.read("xl/workbook.xml"))
            sheets = workbook.find(f"{X}sheets")
            if sheets is None or not len(sheets):
                raise OfficialTemplateBlocked("TEMPLATE_SHEET_MISSING")
            first = sheets[0]
            sheet_name = first.get("name", "")
            rel_id = first.get(f"{R}id")
            rels = ET.fromstring(archive.read("xl/_rels/workbook.xml.rels"))
            target = next((row.get("Target") for row in rels if row.get("Id") == rel_id), None)
            if not target or not target.startswith("worksheets/") or ".." in target:
                raise OfficialTemplateBlocked("TEMPLATE_SHEET_PATH_INVALID")
            path = f"xl/{target}"
            if path not in names:
                raise OfficialTemplateBlocked("TEMPLATE_SHEET_MISSING")
            strings: list[str] = []
            if "xl/sharedStrings.xml" in names:
                shared = ET.fromstring(archive.read("xl/sharedStrings.xml"))
                strings = [
                    "".join(part.text or "" for part in row.iter(f"{X}t"))
                    for row in shared.findall(f"{X}si")
                ]
            sheet = ET.fromstring(archive.read(path))
            rows = sheet.find(f"{X}sheetData")
            if rows is None or not len(rows):
                raise OfficialTemplateBlocked("TEMPLATE_HEADER_MISSING")
            headers: list[str] = []
            for cell in rows[0].findall(f"{X}c"):
                if cell.find(f"{X}f") is not None:
                    raise OfficialTemplateBlocked("TEMPLATE_FORMULA_HEADER")
                if cell.get("t") == "s":
                    try:
                        value = strings[int(cell.findtext(f"{X}v", ""))]
                    except (ValueError, IndexError):
                        raise OfficialTemplateBlocked("TEMPLATE_HEADER_INVALID") from None
                else:
                    value = "".join(node.text or "" for node in cell.iter(f"{X}t"))
                headers.append(value)
            return sheet_name, tuple(headers)
    except (BadZipFile, ET.ParseError, KeyError) as exc:
        raise OfficialTemplateBlocked("TEMPLATE_STRUCTURE_INVALID") from exc


def verify_official_template(blob: bytes, contract: OfficialTemplateContract) -> None:
    if not all((contract.version, contract.approved_by, contract.approval_ref)):
        raise OfficialTemplateBlocked("TEMPLATE_APPROVAL_REQUIRED")
    if hashlib.sha256(blob).hexdigest() != contract.sha256:
        raise OfficialTemplateBlocked("TEMPLATE_HASH_MISMATCH")
    sheet_name, headers = _template_headers(blob)
    if sheet_name != contract.sheet_name or headers != contract.headers:
        raise OfficialTemplateBlocked("TEMPLATE_HEADER_MISMATCH")
    if len(headers) != len(set(headers)) or not headers:
        raise OfficialTemplateBlocked("TEMPLATE_HEADER_INVALID")


def render_verified_bulk(
    *,
    template_blob: bytes,
    contract: OfficialTemplateContract,
    rows: list[Mapping[str, object]],
    explicit_user_confirmation: bool,
) -> bytes:
    """Render only contract-validated rows; caller must separately authorize upload.

    This intentionally does not claim Walmart acceptance of the generated bytes.
    """
    if not explicit_user_confirmation:
        raise OfficialTemplateBlocked("USER_EXPORT_CONFIRMATION_REQUIRED")
    verify_official_template(template_blob, contract)
    if not rows or len(rows) > 20_000:
        raise OfficialTemplateBlocked("BULK_ROW_COUNT_INVALID")
    ordered: list[tuple[object, ...]] = []
    seen: set[tuple[str, str]] = set()
    for row in rows:
        if set(row) != set(contract.headers):
            raise OfficialTemplateBlocked("BULK_ROW_COLUMNS_INVALID")
        if any(
            row.get(key) not in (None, "")
            for key in ("Suggested Bid", "Total Budget", "Item Name")
            if key in contract.headers
        ):
            raise OfficialTemplateBlocked("BULK_SYSTEM_FIELD_MUST_BE_BLANK")
        match = str(row.get("Match Type", ""))
        keyword = str(row.get("Keyword", ""))
        if match not in ("Exact", "Broad") or not keyword:
            raise OfficialTemplateBlocked("BULK_TARGET_INVALID")
        identity = (match, keyword.casefold().strip())
        if identity in seen:
            raise OfficialTemplateBlocked("BULK_DUPLICATE_TARGET")
        seen.add(identity)
        ordered.append(tuple(row[key] for key in contract.headers))
    return _make_xlsx([(contract.sheet_name, contract.headers, ordered)])
